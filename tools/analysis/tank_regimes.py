#!/usr/bin/env python3
"""Four-regime summary of the SPRING TANK level sweeps.

Turns ``level_sweep_pure.csv`` / ``level_sweep_tank*.csv`` (written by
``rvx_measure.py sweep``) into ``build/measures/tank_regimes.md``.

The regimes are defined from the measured behaviour, not from the code:

  A  quiet / linear      THD < 0.3 %, peak gain and RT60 constant, no hits
  B  micro-warm          0.3 % <= THD < 3 %, first measurable darkening
  C  compressed / darker 3 % <= THD < 15 %, noise centroid drops, gain drift
  D  impact / overdrive  THD >= 15 % OR non-harmonic spur > -100 dBFS

Boundaries are read off the TANK Drive=0.5 CSV; the Drive=1.0 CSV is shown
beside it (its whole curve is shifted ~18 dB down because Drive is a pre-gain).

Usage:
  python tools/analysis/tank_regimes.py
  python tools/analysis/tank_regimes.py --measures build/measures \
      --md build/measures/tank_regimes.md
"""

import argparse
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_MEASURES = os.path.join(ROOT, "build", "measures")
DEFAULT_MD = os.path.join(DEFAULT_MEASURES, "tank_regimes.md")

REGIMES = [
    ("A", "quiet / linear", "THD < 0.3 %, every level-dependent metric flat, hit gate closed"),
    ("B", "micro-warm", "0.3 % <= THD < 3 %, harmonic colour only, first darkening"),
    ("C", "compressed / darker", "3 % <= THD < 15 %, noise centroid drops, gain/RT60 drift"),
    ("D", "impact / overdrive", "THD >= 15 % or non-harmonic spur > -100 dBFS, hits audible"),
]


def load(path):
    with open(path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    out = {}
    for r in rows:
        if r.get("error"):
            continue
        out.setdefault(r["test"], []).append(r)
    return out


def fnum(r, key):
    try:
        return float(r[key])
    except (KeyError, TypeError, ValueError):
        return None


def series_by_level(rows, key):
    vals = []
    for r in rows:
        v = fnum(r, key)
        if v is not None:
            vals.append((fnum(r, "level_dbfs"), v))
    return sorted(vals)


def crossing(vals, threshold):
    """First level whose value crosses ``threshold`` upwards."""
    for level, v in vals:
        if v >= threshold:
            return level
    return None


def classify(thd, spur):
    if spur is not None and spur > -100.0:
        return "D"
    if thd is None:
        return None
    if thd >= 15.0:
        return "D"
    if thd >= 3.0:
        return "C"
    if thd >= 0.3:
        return "B"
    return "A"


def regime_rows(tag, data):
    """One row per sine level: level, THD, spur, and the regime it lands in."""
    sine = {fnum(r, "level_dbfs"): r for r in data.get("sine", [])}
    imp = {fnum(r, "level_dbfs"): r for r in data.get("impulse", [])}
    noi = {fnum(r, "level_dbfs"): r for r in data.get("noise", [])}
    rows = []
    for level in sorted(l for l in sine if l is not None):
        s, i, n = sine[level], imp.get(level, {}), noi.get(level, {})
        thd = fnum(s, "thd_pct")
        spur = fnum(s, "spur_dbfs")
        rows.append({
            "tag": tag,
            "level_dbfs": level,
            "thd_pct": thd,
            "thdn_pct": fnum(s, "thdn_pct"),
            "spur_dbfs": spur,
            "imp_peak_gain_db": fnum(i, "peak_gain_db"),
            "t30_s": fnum(i, "rt60_t30_s"),
            "centroid_hz": fnum(i, "centroid_hz"),
            "noise_centroid_hz": fnum(n, "centroid_hz"),
            "noise_rms_dbfs": fnum(n, "rms_dbfs"),
            "event_count": fnum(i, "event_count"),
            "regime": classify(thd, spur),
        })
    return rows


def regime_bounds(rows):
    """First level of each regime, for the Drive=0.5 table."""
    bounds = {}
    for code, _name, _desc in REGIMES:
        hits = [r["level_dbfs"] for r in rows if r["regime"] == code]
        bounds[code] = (min(hits), max(hits)) if hits else None
    return bounds


def _fmt(v, digits=2, suffix=""):
    if v is None:
        return "-"
    return f"{v:.{digits}f}{suffix}"


def _range(b):
    if not b:
        return "-"
    return f"{_fmt(b[0], 1)} … {_fmt(b[1], 1)} dBFS"


def build_markdown(pure, tank, tank_d10, acceptance=None, plugin_sha=None):
    L = ["# SPRING TANK — four-regime level behaviour", ""]
    if plugin_sha:
        L.append(f"- plugin_sha256: `{plugin_sha}`")
    L += ["- source CSVs: `build/measures/level_sweep_pure.csv`, "
          "`level_sweep_tank.csv` (Drive 0.5), `level_sweep_tank_d10.csv` (Drive 1.0)",
          "- generated by `tools/analysis/tank_regimes.py` from the sweep measurements",
          "- PURE is the linear control: every level-dependent metric must stay constant.", ""]

    t_rows = regime_rows("tank", tank)
    d_rows = regime_rows("tank_d10", tank_d10)
    p_rows = regime_rows("pure", pure)
    bounds = regime_bounds(t_rows)

    L += ["## 1. Regime map (TANK, Drive = 0.5 = default)", "",
          "| regime | name | level range | criterion |", "|---|---|---|---|"]
    for code, name, desc in REGIMES:
        L.append(f"| {code} | {name} | {_range(bounds.get(code))} | {desc} |")
    L += [""]

    L += ["## 2. TANK Drive=0.5 — measurements per level", "",
          "| input dBFS | regime | THD % | THD+N % | max spur dBFS | imp peak gain dB |"
          " T30 s | imp centroid Hz | noise centroid Hz | noise RMS dBFS |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in t_rows:
        L.append(f"| {r['level_dbfs']:+.1f} | {r['regime']} | {_fmt(r['thd_pct'], 4)} | "
                 f"{_fmt(r['thdn_pct'], 4)} | {_fmt(r['spur_dbfs'], 1)} | "
                 f"{_fmt(r['imp_peak_gain_db'], 3)} | {_fmt(r['t30_s'], 4)} | "
                 f"{_fmt(r['centroid_hz'], 1)} | {_fmt(r['noise_centroid_hz'], 1)} | "
                 f"{_fmt(r['noise_rms_dbfs'], 2)} |")
    L += [""]

    # quantitative evidence per regime
    L += ["## 3. Evidence per regime (Drive = 0.5)", ""]
    for code, name, desc in REGIMES:
        sel = [r for r in t_rows if r["regime"] == code]
        if not sel:
            continue
        thd = [r["thd_pct"] for r in sel if r["thd_pct"] is not None]
        gain = [r["imp_peak_gain_db"] for r in sel if r["imp_peak_gain_db"] is not None]
        t30 = [r["t30_s"] for r in sel if r["t30_s"] is not None]
        cen = [r["centroid_hz"] for r in sel if r["centroid_hz"] is not None]
        ncen = [r["noise_centroid_hz"] for r in sel if r["noise_centroid_hz"] is not None]
        spur = [r["spur_dbfs"] for r in sel if r["spur_dbfs"] is not None]
        L += [f"**{code} — {name}** ({_range(bounds[code])}): {desc}.", "",
              f"- THD {min(thd):.4f}–{max(thd):.4f} %; peak gain "
              f"{min(gain):.3f}–{max(gain):.3f} dB (drift {max(gain) - min(gain):.3f} dB); "
              f"T30 {min(t30):.4f}–{max(t30):.4f} s; impulse centroid "
              f"{min(cen):.1f}–{max(cen):.1f} Hz; noise centroid "
              f"{min(ncen):.1f}–{max(ncen):.1f} Hz; max non-harmonic spur "
              f"{max(spur):.1f} dBFS.",
              ""]

    # Drive 1.0
    thd_05 = series_by_level(tank.get("sine", []), "thd_pct")
    thd_10 = series_by_level(tank_d10.get("sine", []), "thd_pct")
    L += ["## 4. Drive=1.0", "",
          "Drive=1.0 is a **different voicing**, not merely a level shift:"
          " `driveNorm=1` shortens the tank RT60 (~1.68 s vs 2.565 s) and moves"
          " the post-tone low-pass down, so the centroid drops (~684 Hz vs 730 Hz)."
          " Its THD curve reaches the same thresholds at almost the same input"
          " levels as Drive=0.5, but its hit gate opens ~18 dB earlier because the"
          " gate sees the program input multiplied by the drive gain.", "",
          "| boundary | Drive 0.5 | Drive 1.0 |", "|---|---|---|"]
    for label, thr in (("THD >= 0.3 %", 0.3), ("THD >= 3 %", 3.0), ("THD >= 15 %", 15.0)):
        L.append(f"| {label} | {_fmt(crossing(thd_05, thr), 1)} dBFS | "
                 f"{_fmt(crossing(thd_10, thr), 1)} dBFS |")
    L += ["", "| input dBFS | Drive 0.5 THD % | Drive 1.0 THD % | Drive 0.5 regime |"
          " Drive 1.0 regime |", "|---|---|---|---|---|"]
    d_by_level = {r["level_dbfs"]: r for r in d_rows}
    for r in t_rows:
        near = d_by_level.get(r["level_dbfs"])
        L.append(f"| {r['level_dbfs']:+.1f} | {_fmt(r['thd_pct'], 4)} | "
                 f"{_fmt(near['thd_pct'], 4) if near else '-'} | {r['regime']} | "
                 f"{near['regime'] if near else '-'} |")
    L += [""]

    # PURE control
    gains = [fnum(r, "peak_gain_db") for r in pure.get("impulse", []) if fnum(r, "peak_gain_db") is not None]
    t30s = [fnum(r, "rt60_t30_s") for r in pure.get("impulse", []) if fnum(r, "rt60_t30_s") is not None]
    thds = [fnum(r, "thd_pct") for r in pure.get("sine", []) if fnum(r, "thd_pct") is not None]
    L += ["## 5. PURE control", ""]
    if gains and t30s and thds:
        L += [f"- peak gain {min(gains):.3f} … {max(gains):.3f} dB "
              f"(spread {max(gains) - min(gains):.4f} dB over the whole sweep)",
              f"- T30 {min(t30s):.4f} … {max(t30s):.4f} s "
              f"(spread {max(t30s) - min(t30s):.4f} s)",
              f"- THD {min(thds):.2e} … {max(thds):.2e} % — numerically linear at all levels",
              "- conclusion: PURE does not enter any regime; it is the linear reference"
              " and stays bit-exact against the golden capture."]
    L += [""]

    if acceptance:
        gate = (acceptance.get("hits") or {}).get("gate") or {}
        thr = gate.get("threshold_dbfs") or {}
        L += ["## 6. Hit gate (from TANK_ACCEPTANCE.md)", "",
              "The impact layer is gated on `20*log10(|excite|*driveGain) > -12 dB`."
              " Measured on a 1 kHz sine:", "",
              "| Drive | first input level with hits |", "|---|---|"]
        for d in ("0.5", "1.0"):
            L.append(f"| {d} | {_fmt(thr.get(d), 1)} dBFS |")
        L += ["", "A -6 dBFS sine therefore only excites the impact layer at"
              " Drive 1.0 (where the register output is already ~-7 dBFS); at"
              " Drive 0.5 nothing fires below ~+0.7 dBFS.", ""]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--measures", default=DEFAULT_MEASURES)
    ap.add_argument("--md", default=DEFAULT_MD)
    ap.add_argument("--acceptance", default=None,
                    help="tank_acceptance.json (default: <measures>/tank_acceptance/tank_acceptance.json)")
    args = ap.parse_args()

    pure = load(os.path.join(args.measures, "level_sweep_pure.csv"))
    tank = load(os.path.join(args.measures, "level_sweep_tank.csv"))
    tank_d10 = load(os.path.join(args.measures, "level_sweep_tank_d10.csv"))

    acc_path = args.acceptance or os.path.join(args.measures, "tank_acceptance",
                                               "tank_acceptance.json")
    acceptance = None
    if os.path.exists(acc_path):
        with open(acc_path, encoding="utf-8") as fh:
            acceptance = json.load(fh)

    md = build_markdown(pure, tank, tank_d10, acceptance,
                        acceptance.get("plugin_sha256") if acceptance else None)
    with open(args.md, "w", encoding="utf-8") as fh:
        fh.write(md)
    print(f"wrote {args.md}")
    print(md)


if __name__ == "__main__":
    main()
